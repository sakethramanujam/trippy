import SwiftUI

// MARK: - Shared trip row for pickers

struct PickerTripRow: View {
    let trip: ApiTrip
    let snap: TripSnapshot
    var selected: Bool
    var multi: Bool
    var journeyName: String?

    var body: some View {
        HStack(spacing: 12) {
            Image(systemName: selected ? (multi ? "checkmark.circle.fill" : "largecircle.fill.circle") : "circle")
                .type(.title3)
                .foregroundStyle(selected ? Theme.blue : Theme.textTertiary)
            VStack(alignment: .leading, spacing: 2) {
                HStack(spacing: 6) {
                    Text(trip.displayTitle).type(.headline).foregroundStyle(.white).lineLimit(1)
                    if trip.isAutoGenerated { AutoTag() }
                }
                HStack(spacing: 6) {
                    Text(snap.dateRange.map { range in
                        snap.start.map { "\(range), \(Calendar.current.component(.year, from: $0))" } ?? range
                    } ?? "No dates")
                    if !snap.routeCodes.isEmpty { Text("•"); Text(snap.routeCodes).lineLimit(1) }
                }
                .type(.footnote).monospacedDigit()
                .foregroundStyle(Theme.textSecondary)
                if let journeyName {
                    Label(journeyName, systemImage: "link").type(.caption).foregroundStyle(Theme.blue).lineLimit(1)
                }
            }
            Spacer(minLength: 0)
        }
        .padding(.vertical, 10)
        .contentShape(Rectangle())
    }
}

/// Trips sorted newest first, filtered by a search string (title, city codes, year).
@MainActor private func searchTrips(_ network: NetworkManager, _ query: String, exclude: Set<Int>) -> [TripSnapshot] {
    let now = Date()
    let q = query.trimmingCharacters(in: .whitespaces).lowercased()
    return network.trips
        .filter { !exclude.contains($0.id) }
        .map { TripSnapshot(trip: $0, allRentals: network.rentals, now: now) }
        .filter { s in
            guard !q.isEmpty else { return true }
            let hay = [s.trip.displayTitle, s.routeCodes, s.stops.compactMap(\.city).joined(separator: " "),
                       s.year > 0 ? String(s.year) : ""].joined(separator: " ").lowercased()
            return hay.contains(q)
        }
        .sorted { ($0.start ?? .distantPast) > ($1.start ?? .distantPast) }
}

// MARK: - Generic trip picker (Add trip…, Merge into…, Move to trip…)

struct TripPickerSheet: View {
    @ObservedObject var network: NetworkManager
    let title: String
    var subtitle: String?
    var confirm: String
    var multi: Bool
    var exclude: Set<Int> = []
    var allowNone = false
    var destructive = false
    /// (picked trip ids, "No trip" chosen)
    let onPick: ([Int], Bool) -> Void

    @Environment(\.dismiss) private var dismiss
    @State private var query = UserDefaults.standard.string(forKey: "TrippyPickerQuery") ?? ""
    @State private var picked: [Int] = []
    @State private var none = false

    var body: some View {
        NavigationStack {
            List {
                if let subtitle {
                    Text(subtitle).type(.footnote).foregroundStyle(Theme.textSecondary)
                        .listRowBackground(Color.clear)
                }
                if allowNone {
                    Button {
                        Haptics.tap(); none = true; picked = []
                    } label: {
                        HStack(spacing: 12) {
                            Image(systemName: none ? "largecircle.fill.circle" : "circle").type(.title3)
                                .foregroundStyle(none ? Theme.blue : Theme.textTertiary)
                            VStack(alignment: .leading, spacing: 2) {
                                Text("No trip").type(.headline).foregroundStyle(.white)
                                Text("Keep it, but not on any trip").type(.footnote).foregroundStyle(Theme.textSecondary)
                            }
                        }
                        .padding(.vertical, 6)
                    }
                    .buttonStyle(.plain)
                    .listRowBackground(Theme.surface)
                }
                let rows = searchTrips(network, query, exclude: exclude)
                Section {
                    ForEach(rows, id: \.id) { snap in
                        Button { toggle(snap.id) } label: {
                            PickerTripRow(trip: snap.trip, snap: snap, selected: picked.contains(snap.id), multi: multi,
                                          journeyName: network.journey(of: snap.trip)?.title)
                        }
                        .buttonStyle(.plain)
                        .listRowBackground(Theme.surface)
                    }
                } header: {
                    Text("\(rows.count) trips").type(.label)
                }
            }
            .scrollContentBackground(.hidden)
            .background(Theme.sheet)
            .searchable(text: $query, placement: .navigationBarDrawer(displayMode: .always), prompt: "Search trips, cities, years")
            .navigationTitle(title)
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) { Button("Cancel") { dismiss() } }
                ToolbarItem(placement: .confirmationAction) {
                    Button(picked.count > 1 ? "\(confirm) (\(picked.count))" : confirm) {
                        onPick(picked, none)
                        dismiss()
                    }
                    .fontWeight(.semibold)
                    .tint(destructive ? Theme.red : Theme.blue)
                    .disabled(picked.isEmpty && !none)
                }
            }
        }
        .preferredColorScheme(.dark)
        .presentationDetents([.large])
        .onAppear {
            if let pre = UserDefaults.standard.string(forKey: "TrippyPickerSelect") {
                picked = pre.split(separator: ",").compactMap { Int($0) }.filter { id in network.trips.contains { $0.id == id } }
                if !multi { picked = Array(picked.prefix(1)) }
            }
        }
    }

    private func toggle(_ id: Int) {
        Haptics.tap()
        none = false
        if multi {
            if let i = picked.firstIndex(of: id) { picked.remove(at: i) } else { picked.append(id) }
        } else {
            picked = [id]
        }
    }
}

// MARK: - Link to journey (manual linking)

/// From a trip's ⋯ menu or the Trips list's multi-select: add the chosen trips to an existing journey,
/// or start a new one (title prefilled from the route). The trip list is searchable so you can pull
/// in more trips at the same time.
struct LinkToJourneySheet: View {
    @ObservedObject var network: NetworkManager
    let seed: [Int]
    var onLinked: (Int) -> Void = { _ in }

    @Environment(\.dismiss) private var dismiss
    @State private var picked: [Int] = []
    @State private var target: Int?            // nil = new journey
    @State private var title = ""
    @State private var titleEdited = false
    @State private var query = ""
    @State private var busy = false
    @State private var errorText: String?

    var body: some View {
        NavigationStack {
            List {
                Section {
                    destinationRow(nil)
                    if target == nil {
                        TextField("Journey title", text: Binding(get: { title }, set: { title = $0; titleEdited = true }))
                            .type(.body)
                            .listRowBackground(Theme.surface)
                    }
                    ForEach(network.journeys.filter(\.is_owner)) { j in destinationRow(j) }
                } header: {
                    Text("Link into").type(.label)
                }

                Section {
                    ForEach(searchTrips(network, query, exclude: excluded), id: \.id) { snap in
                        Button { toggle(snap.id) } label: {
                            PickerTripRow(trip: snap.trip, snap: snap, selected: picked.contains(snap.id), multi: true,
                                          journeyName: network.journey(of: snap.trip)?.title)
                        }
                        .buttonStyle(.plain)
                        .listRowBackground(Theme.surface)
                    }
                } header: {
                    Text("Trips to link • \(picked.count) selected").type(.label)
                } footer: {
                    Text("Linking keeps every trip as it is. You can remove a trip from the journey later.")
                        .type(.caption)
                }

                if let errorText {
                    FormErrorBanner(message: errorText).listRowBackground(Color.clear)
                }
            }
            .scrollContentBackground(.hidden)
            .background(Theme.sheet)
            .searchable(text: $query, placement: .navigationBarDrawer(displayMode: .always), prompt: "Search trips to add")
            .navigationTitle("Link to journey")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) { Button("Cancel") { dismiss() } }
                ToolbarItem(placement: .confirmationAction) {
                    Button(target == nil ? "Create" : "Link") { Task { await save() } }
                        .fontWeight(.semibold)
                        .disabled(busy || picked.isEmpty || (target == nil && picked.count < 1))
                }
            }
        }
        .preferredColorScheme(.dark)
        .task {
            picked = seed
            if network.journeys.isEmpty { await network.fetchJourneys() }
            if let jid = UserDefaults.standard.string(forKey: "TrippyLinkTarget").flatMap(Int.init) { target = jid }
            if let more = UserDefaults.standard.string(forKey: "TrippyPickerSelect") {
                for id in more.split(separator: ",").compactMap({ Int($0) }) where !picked.contains(id) && network.trips.contains(where: { $0.id == id }) {
                    picked.append(id)
                }
            }
            await refreshTitle()
        }
        .onChange(of: picked) { _, _ in Task { await refreshTitle() } }
    }

    /// Trips already in the chosen journey aren't offered again.
    private var excluded: Set<Int> {
        guard let target, let j = network.journeys.first(where: { $0.id == target }) else { return [] }
        return Set(j.trip_ids)
    }

    private func destinationRow(_ j: ApiJourney?) -> some View {
        let on = target == j?.id
        return Button {
            Haptics.tap()
            target = j?.id
        } label: {
            HStack(spacing: 12) {
                Image(systemName: j == nil ? "plus.square.on.square" : "square.stack.3d.up.fill")
                    .type(.headline).foregroundStyle(j == nil ? Theme.green : Theme.blue)
                    .frame(width: 28)
                VStack(alignment: .leading, spacing: 2) {
                    Text(j?.title ?? "New journey").type(.headline).foregroundStyle(.white).lineLimit(1)
                    Text(j.map { "\($0.trip_count) trips • \($0.dateText)" } ?? "Start a journey from the selected trips")
                        .type(.footnote).foregroundStyle(Theme.textSecondary).lineLimit(1)
                }
                Spacer()
                if on { Image(systemName: "checkmark").type(.headline).foregroundStyle(Theme.blue) }
            }
            .padding(.vertical, 4)
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .listRowBackground(on ? Theme.blue.opacity(0.14) : Theme.surface)
    }

    private func toggle(_ id: Int) {
        Haptics.tap()
        if let i = picked.firstIndex(of: id) { picked.remove(at: i) } else { picked.append(id) }
    }

    private func refreshTitle() async {
        guard !titleEdited, !picked.isEmpty else { return }
        if let t = await network.suggestJourneyTitle(picked) { title = t }
    }

    private func save() async {
        busy = true
        defer { busy = false }
        if let target {
            let ids = picked.filter { !excluded.contains($0) }
            if let err = await network.addTrips(ids, toJourney: target) { errorText = err; return }
            Haptics.success()
            onLinked(target)
        } else {
            let (id, err) = await network.createJourney(title: title, tripIds: picked)
            if let err { errorText = err; return }
            Haptics.success()
            if let id { onLinked(id) }
        }
        dismiss()
    }
}

// MARK: - Move bookings to another trip

struct MoveToTripSheet: View {
    @ObservedObject var network: NetworkManager
    let items: [ItemRef]
    var fromTrip: Int?
    /// Called after the move with the server's error, if any.
    var onDone: (String?) async -> Void = { _ in }

    var body: some View {
        TripPickerSheet(network: network, title: items.count == 1 ? "Move to trip" : "Move \(items.count) items",
                        subtitle: summary, confirm: "Move", multi: false,
                        exclude: fromTrip.map { [$0] } ?? [],
                        allowNone: !items.contains { $0.kind == .expense }) { ids, none in
            Task {
                let err = await network.moveItems(items, to: none ? nil : ids.first)
                if err == nil { Haptics.success() }
                await onDone(err)
            }
        }
    }

    private var summary: String {
        let counts = Dictionary(grouping: items, by: \.kind).mapValues(\.count)
        let names: [(ItemRef.Kind, String)] = [(.flight, "flight"), (.lodging, "stay"), (.rental, "rental"), (.expense, "expense")]
        var parts: [String] = []
        for (k, n) in names { if let c = counts[k] { parts.append("\(c) \(n)\(c == 1 ? "" : "s")") } }
        return "Moving \(parts.joined(separator: ", ")). Nothing is deleted."
    }
}

// MARK: - Reorder legs

struct ReorderJourneySheet: View {
    @ObservedObject var network: NetworkManager
    let journey: ApiJourney
    var onDone: () async -> Void

    @Environment(\.dismiss) private var dismiss
    @State private var legs: [ApiJourneyLeg] = []

    var body: some View {
        NavigationStack {
            List {
                ForEach(Array(legs.enumerated()), id: \.element.id) { idx, leg in
                    HStack(spacing: 12) {
                        Text("\(idx + 1)").type(.numberSmall).foregroundStyle(.black)
                            .frame(width: 24, height: 24)
                            .background(JourneyPalette.color(idx + 1), in: Circle())
                        VStack(alignment: .leading, spacing: 2) {
                            Text(leg.title).type(.headline).foregroundStyle(.white)
                            Text(Fmt.parse(leg.start_date).map(Fmt.monthDayYear) ?? "No dates")
                                .type(.footnote).foregroundStyle(Theme.textSecondary)
                        }
                    }
                    .listRowBackground(Theme.surface)
                }
                .onMove { legs.move(fromOffsets: $0, toOffset: $1) }
            }
            .environment(\.editMode, .constant(.active))
            .scrollContentBackground(.hidden)
            .background(Theme.sheet)
            .navigationTitle("Reorder trips")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .cancellationAction) { Button("Cancel") { dismiss() } }
                ToolbarItem(placement: .confirmationAction) {
                    Button("Save") {
                        Task {
                            _ = await network.reorderJourney(journey.id, tripIds: legs.map(\.trip_id))
                            await onDone()
                            dismiss()
                        }
                    }
                    .fontWeight(.semibold)
                }
            }
        }
        .preferredColorScheme(.dark)
        .onAppear { legs = journey.legs ?? [] }
    }
}
